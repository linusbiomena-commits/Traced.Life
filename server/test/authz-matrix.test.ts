import { randomUUID } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { setupTestApp, type TestClient, type TestEnv } from './helpers/test-app.ts';

// Phase 7 authorization sweep: every registered API route is called as every role. A route is
// "reachable" for a role when the request gets past authentication/authorisation (any status
// other than 401/403). Each role may only reach routes in its own areas; anything else fails the
// test. Bodies are empty and ids random, so nothing is changed. With UPDATE_MATRIX=1 the observed
// matrix is written to docs/security/permission-matrix.md.

let t: TestEnv;
const roles: Record<string, TestClient> = {};
beforeAll(async () => {
  t = await setupTestApp();
  t.config.auditCheckpointKey = 'k'.repeat(44); // so the manual checkpoint route can succeed
  roles.anonymous = t.client();
  roles.customer = (await t.customer()).c;
  roles.collection_staff = (await t.staff(['collection_staff'])).c;
  roles.lab_operator = (await t.mfaStaff(['lab_operator'])).c;
  roles.auditor = (await t.mfaStaff(['auditor'])).c;
  roles.admin = (await t.mfaStaff(['admin'])).c;
  roles.super_admin = (await t.mfaStaff(['super_admin'])).c;
});
afterAll(async () => t.close());

const SELF = ['GET /auth/me', 'POST /auth/sign-out', 'POST /auth/verify-email/resend', 'POST /auth/password/change', 'POST /auth/mfa/setup', 'POST /auth/mfa/enable', 'POST /auth/mfa/verify', 'GET /me/profile', 'PATCH /me/profile', 'POST /auth/mfa/recovery-codes'];
const PUBLIC = ['GET /health', 'POST /auth/sign-up', 'POST /auth/verify-email', 'POST /auth/sign-in', 'POST /auth/password/forgot', 'POST /auth/password/reset', 'POST /auth/account-setup'];
/** Which routes each role may get past authorisation on (by prefix or exact "METHOD /path"). */
const ALLOWED: Record<string, (route: string) => boolean> = {
  anonymous: (r) => PUBLIC.includes(r),
  customer: (r) => PUBLIC.includes(r) || SELF.includes(r) || / \/me\//.test(r),
  collection_staff: (r) => PUBLIC.includes(r) || SELF.includes(r) || / \/staff\//.test(r),
  lab_operator: (r) => PUBLIC.includes(r) || SELF.includes(r) || / \/lab\//.test(r),
  auditor: (r) => PUBLIC.includes(r) || SELF.includes(r) || ['GET /admin/stats', 'GET /admin/audit-logs', 'GET /admin/reports/operational.csv', 'GET /admin/audit-integrity', 'POST /admin/audit-integrity/verify'].includes(r),
  // Admins hold custody.record_lab by the Phase 1 catalogue (they cover laboratory duties until a
  // laboratory role is approved), so the operational-only lab API is intentionally reachable.
  admin: (r) => PUBLIC.includes(r) || SELF.includes(r) || / \/(admin|lab)\//.test(r),
  super_admin: (r) => PUBLIC.includes(r) || SELF.includes(r) || / \/(admin|lab)\//.test(r),
};
// Admin-area routes an ordinary admin must NOT reach (super-admin only).
const SUPER_ONLY = ['POST /admin/exports/personal-data', 'POST /admin/staff/:id/mfa-reset', 'POST /admin/audit-integrity/checkpoint'];
const SKIP = new Set(['POST /auth/sign-out', 'POST /internal/outbox/run', 'POST /internal/audit/checkpoint']);

describe('authorization sweep over every API route', () => {
  it('each role reaches only the routes of its own areas; super-admin-only routes stay super-admin only', async () => {
    const routes = [...new Map(t.app.routes.filter((r) => r.method !== 'ALL' && r.path.startsWith('/api/v1/'))
      .map((r) => [`${r.method} ${r.path.replace('/api/v1', '')}`, { method: r.method, path: r.path.replace('/api/v1', '') }])).values()];
    expect(routes.length).toBeGreaterThan(80);
    const matrix: Record<string, Record<string, number>> = {};
    const violations: string[] = [];
    for (const { method, path: p } of routes) {
      const key = `${method} ${p}`;
      if (SKIP.has(key)) continue;
      const concrete = p.replace(/:[a-zA-Z]+/g, randomUUID());
      matrix[key] = {};
      for (const [role, c] of Object.entries(roles)) {
        const res = await c.request(method, concrete, method === 'GET' ? undefined : {});
        matrix[key][role] = res.status;
        const reachable = res.status !== 401 && res.status !== 403;
        if (reachable && !ALLOWED[role]!(key)) violations.push(`${role} reached ${key} (${res.status})`);
        if (reachable && role === 'admin' && SUPER_ONLY.includes(key)) violations.push(`admin reached super-admin-only ${key} (${res.status})`);
        if (res.status >= 500) violations.push(`${role} got ${res.status} on ${key}`);
      }
    }
    expect(violations).toEqual([]);
    if (process.env.UPDATE_MATRIX === '1') {
      const names = Object.keys(roles);
      const cell = (s: number) => (s === 401 || s === 403 ? '–' : '✓');
      const lines = [
        '# TRACED: Observed API permission matrix',
        '',
        `Generated by \`server/test/authz-matrix.test.ts\` (UPDATE_MATRIX=1) on ${new Date().toISOString().slice(0, 10)}. ✓ = gets past authentication and authorisation (the request may still fail validation or find nothing); – = refused (401/403). Privileged roles are signed in with MFA completed. Object-level checks (own registration, assigned branch) are tested separately.`,
        '',
        `| Route | ${names.join(' | ')} |`, `|---|${names.map(() => '---').join('|')}|`,
        ...Object.entries(matrix).sort(([a], [b]) => a.split(' ')[1]!.localeCompare(b.split(' ')[1]!)).map(([k, v]) => `| \`${k}\` | ${names.map((n) => cell(v[n]!)).join(' | ')} |`),
        '',
        'Not swept (would end the session or need a scheduler credential): `POST /auth/sign-out`, `POST /internal/*` (secret or Google-signed token required; see docs/deploy/phase-8-plan.md).',
      ];
      mkdirSync(path.resolve('docs/security'), { recursive: true });
      writeFileSync(path.resolve('docs/security/permission-matrix.md'), `${lines.join('\n')}\n`);
    }
  }, 240_000);
});
